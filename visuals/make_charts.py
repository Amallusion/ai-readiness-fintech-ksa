# 5. Where the tier cuts came from
# ---------------------------------------------------------------------
def chart5_gaps(tiers):
    """A tier boundary at a round number invites the question of whether it was
    chosen to produce a convenient answer. The honest defence is to show the
    gaps and let the reader judge, including where the answer is partial.

    Both cuts land inside genuine discontinuities — the 900 cut in the second
    largest gap in the distribution, the 450 cut in the third — rather than
    slicing through a dense run of sectors. The single largest gap sits between
    the two fastest sectors, above both cuts, so it is not a candidate boundary.
    """
    s = tiers.sort_values("Index_Dec2023").reset_index(drop=True)
    vals = s["Index_Dec2023"].values
    gaps = np.diff(vals)
    rank = {i: r + 1 for r, i in enumerate(np.argsort(gaps)[::-1])}
    contains = {}
    for i in range(len(gaps)):
        for cut in (CUT_SLOW, CUT_RAPID):
            if vals[i] < cut < vals[i + 1]:
                contains[i] = cut

    fig, ax = plt.subplots(figsize=(12, 5))
    ax.scatter(vals, np.zeros(len(vals)), s=75, color=s["Tier"].map(TIER_COLORS),
               zorder=5, edgecolors="white", linewidths=0.9)
    for i, g in enumerate(gaps):
        mid = (vals[i] + vals[i + 1]) / 2
        if i in contains:
            ax.plot([vals[i], vals[i + 1]], [0, 0], color=INK, lw=4, zorder=3)
            ax.annotate(f"gap {g:.0f}\n({rank[i]}{'st' if rank[i]==1 else 'nd' if rank[i]==2 else 'rd' if rank[i]==3 else 'th'} largest)",
                        (mid, 0), textcoords="offset points", xytext=(0, 20),
                        ha="center", fontsize=9, fontweight="bold", color=INK)
        elif rank[i] == 1:
            ax.plot([vals[i], vals[i + 1]], [0, 0], color="#999", lw=3, zorder=2)
            ax.annotate(f"largest gap ({g:.0f})\nbut both sectors sit\nabove either cut",
                        (mid, 0), textcoords="offset points", xytext=(0, -52),
                        ha="center", fontsize=8, color="#888")
        else:
            ax.annotate(f"{g:.0f}", (mid, 0), textcoords="offset points",
                        xytext=(0, -18), ha="center", fontsize=7, color="#bbb")

    for cut in (CUT_SLOW, CUT_RAPID):
        ax.axvline(cut, color="#555", ls=":", lw=1.5)
        ax.annotate(f"cut at {cut}", (cut, 0), textcoords="offset points",
                    xytext=(0, 54), ha="center", fontsize=9, color="#555")

    ax.set_yticks([])
    ax.set_ylim(-0.85, 0.85)
    ax.set_xlabel("Index, Dec 2023 (Jan 2019 = 100) — each dot is one sector")
    ax.set_title("The tier cuts are choices, so here is the evidence for them\n"
                 "Both fall inside real discontinuities rather than slicing "
                 "through a dense run of sectors",
                 fontsize=12)
    ax.grid(alpha=0.13, axis="x")
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, "chart5_tier_cut_justification.png"))
    plt.close(fig)
    return [(f"cut {c}: gap {gaps[i]:.0f} ({vals[i]:.0f}->{vals[i+1]:.0f}), "
             f"rank {rank[i]} of {len(gaps)}") for i, c in contains.items()]


def main():
    tiers_path = os.path.join(IN_DIR, "sector_growth_tiers.csv")
    idx_path = os.path.join(IN_DIR, "sector_matrix_indexed.csv")
    wide_path = os.path.join(IN_DIR, "preprocessed_wide.csv")

    if os.path.exists(idx_path):
        indexed = pd.read_csv(idx_path)
        last = indexed.columns[-1]
        tiers = indexed[["Sector", last]].copy()
        tiers.columns = ["Sector", "Index_Dec2023"]
        tiers["Tier"] = tiers["Index_Dec2023"].apply(bin_growth_tier)
        tiers.sort_values("Index_Dec2023", ascending=False).to_csv(
            os.path.join(OUT_DIR, "sector_growth_tiers.csv"), index=False)
        chart1_lines(indexed, tiers)
        print("  chart1_all_sectors_indexed.png")
    elif os.path.exists(tiers_path):
        tiers = pd.read_csv(tiers_path)
        print("  chart1 SKIPPED — sector_matrix_indexed.csv not found")
    else:
        raise FileNotFoundError(
            "Need sector_matrix_indexed.csv or sector_growth_tiers.csv in this folder.")

    chart2_ranking(tiers);  print("  chart2_growth_ranking.png")

    if os.path.exists(wide_path):
        chart3_covid(pd.read_csv(wide_path)); print("  chart3_ecommerce_covid_spike.png")
    else:
        print("  chart3 SKIPPED — preprocessed_wide.csv not found")

    lo, hi = chart4_iqr(tiers);  print("  chart4_iqr_fences.png")
    cuts = chart5_gaps(tiers);   print("  chart5_tier_cut_justification.png")

    print(f"\nIQR fences: [{lo:.0f}, {hi:.0f}]")
    print(f"Slowest sector {tiers['Index_Dec2023'].min():.0f} — "
          f"{'flagged' if tiers['Index_Dec2023'].min() < lo else 'NOT flagged'}")
    for line in cuts:
        print("  " + line)
    print(f"Tier cuts at {CUT_SLOW} and {CUT_RAPID}")


if __name__ == "__main__":
    main()
