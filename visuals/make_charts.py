# 4. IQR fences — the outlier test that did not confirm what we expected
# ---------------------------------------------------------------------
def chart4_iqr(tiers):
    """Draws the result we report rather than the one we hoped for.

    Jewelry is clearly the lowest sector, but with 16 observations the
    1.5xIQR fences are wide enough that it is not formally flagged. The
    test flags the opposite extreme instead. Showing this makes the
    honest-reporting claim in the write-up something a reader can check
    rather than something they have to accept.
    """
    v = tiers["Index_Dec2023"]
    q1, q3 = v.quantile(0.25), v.quantile(0.75)
    iqr = q3 - q1
    lo, hi = q1 - 1.5 * iqr, q3 + 1.5 * iqr

    fig, ax = plt.subplots(figsize=(11, 4.6))
    ax.axvspan(max(lo, 0), hi, color="#eef3f7", zorder=0)
    bp = ax.boxplot(v, vert=False, widths=0.42, patch_artist=True,
                    medianprops=dict(color=INK, lw=1.6),
                    boxprops=dict(facecolor="#dce6ee", edgecolor="#7a8b99"),
                    whiskerprops=dict(color="#7a8b99"),
                    capprops=dict(color="#7a8b99"),
                    flierprops=dict(marker="o", markerfacecolor=RAPID,
                                    markeredgecolor=RAPID, markersize=9))
    jitter = np.random.default_rng(7).normal(0, 0.055, len(v))
    ax.scatter(v, 1 + jitter, s=44, color=SLOW, alpha=0.55, zorder=4,
               edgecolors="white", linewidths=0.6)

    if hi < v.max():
        ax.axvline(hi, color=RAPID, ls="--", lw=1.3)
        ax.annotate(f"upper fence {hi:.0f}\nMiscellaneous flagged", (hi, 1.33),
                    textcoords="offset points", xytext=(8, 0), fontsize=8.5,
                    color=RAPID, va="center")
    jew = v.min()
    ax.scatter([jew], [1], s=95, facecolors="none", edgecolors=SLOW,
               linewidths=2, zorder=6)
    ax.annotate(f"Jewelry, {jew:.0f}\nlowest of the 16, and still\n"
                f"{jew - lo:.0f} points inside the lower fence",
                xy=(jew, 1), xytext=(jew + 210, 1.42),
                fontsize=8.5, color=SLOW, va="center",
                arrowprops=dict(arrowstyle="->", color=SLOW, lw=1.2,
                                connectionstyle="arc3,rad=-0.25"))
    if lo < 0:
        ax.annotate(f"Lower fence sits at {lo:.0f} — off the scale, and a negative\n"
                    f"index is impossible. With n=16 the fences are simply too\n"
                    f"wide to flag anything on the low side.",
                    xy=(0.012, 0.06), xycoords="axes fraction",
                    fontsize=8.5, color="#666", va="bottom")

    ax.set_yticks([])
    ax.set_xlabel("Index, Dec 2023 (Jan 2019 = 100)")
    ax.set_title("The outlier test did not confirm what we expected, and we report that\n"
                 f"1.5×IQR on 16 sectors: fences at {lo:.0f} and {hi:.0f}. "
                 "The slowest sector is not flagged; the fastest is",
                 fontsize=12)
    ax.grid(alpha=0.13, axis="x")
    fig.tight_layout()
    fig.savefig(os.path.join(OUT_DIR, "chart4_iqr_fences.png"))
    plt.close(fig)
    return lo, hi


